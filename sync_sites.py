#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
sync_sites.py - downloads real endpoint lists from public GitHub projects
and rebuilds sites.txt. Run this once, then run bomber.py.
"""

import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "sites.txt")
BACKUP = os.path.join(HERE, "sites_backup.txt")

SOURCES = [
    "https://gist.githubusercontent.com/spenkk/af31fd6c4ebeaa15cf6996826109334a/raw",
    "https://raw.githubusercontent.com/Hamed-Fakoori/sms-bomber/main/providers.json",
    "https://raw.githubusercontent.com/Hamed-Fakoori/sms-bomber/master/providers.json",
    "https://raw.githubusercontent.com/AvinashReddy3108/YetAnotherSMSBomber/master/api_config.json",
    "https://raw.githubusercontent.com/AvinashReddy3108/YetAnotherSMSBomber/master/services.yaml",
    "https://raw.githubusercontent.com/hack-parthsharma/YetAnotherSMSBomber/master/api_config.json",
    "https://raw.githubusercontent.com/gh0stlung/ULTIMATE-SMS-BOMBER-/main/api.json",
    "https://raw.githubusercontent.com/WeAreTeamX/xbomber-node-community-edition/main/api.json",
    "https://raw.githubusercontent.com/shibu883/xbomber/main/api.json",
]

URL_RE = re.compile(r"https?://[^\s\"'<>\)\]\},]+")
PLACEHOLDERS = ("{mobile}", "{number}", "{phone_number}", "{phoneNumber}",
                "{tel}", "{msisdn}", "{mobileNumber}", "{phone}",
                "<phone>", "<mobile>", "<number>", "{0}")
KEEP_WORDS = ("otp", "sms", "code", "verify", "verif", "auth", "login",
              "send", "mobile", "phone", "signup", "register", "token")


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", "ignore")


def clean(u):
    u = u.strip().rstrip(",;.'\"")
    u = u.replace("&amp;", "&").replace("\\/", "/")
    for ph in PLACEHOLDERS:
        u = u.replace(ph, "{phone}")
    u = re.sub(r"(\+?\d{1,3})?\{phone\}", "{phone}", u)
    return u


def interesting(u):
    if len(u) < 14 or len(u) > 300:
        return False
    if "github" in u or "githubusercontent" in u:
        return False
    if not u.startswith("http"):
        return False
    low = u.lower()
    return any(w in low for w in KEEP_WORDS)


def main():
    print("=" * 56)
    print("        S Y N C   S I T E S")
    print("=" * 56)

    found = {}
    for src in SOURCES:
        try:
            txt = fetch(src)
        except Exception as e:
            print(f"  x  {src.split('/')[-1]:45} {type(e).__name__}")
            continue
        new = 0
        for u in URL_RE.findall(txt):
            u = clean(u)
            if interesting(u) and u not in found:
                found[u] = True
                new += 1
        print(f"  +  {src.split('/')[-1]:45} {new} new")

    if not found:
        print("\n[X] nothing downloaded. Check your internet.")
        input("\nPress Enter to exit...")
        return

    urls = sorted(found)
    print(f"\n[*] total unique endpoints: {len(urls)}")

    if os.path.exists(OUT) and not os.path.exists(BACKUP):
        os.rename(OUT, BACKUP)
        print(f"[*] old sites.txt saved as sites_backup.txt")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# auto-generated by sync_sites.py\n")
        f.write("# format: URL|METHOD|PAYLOAD\n\n")
        for u in urls:
            if "{phone}" in u:
                f.write(f"{u}|GET|\n")
            else:
                f.write(f'{u}|POST|{{"phone":"{{phone}}"}}\n')

    print(f"[*] wrote {len(urls)} lines to sites.txt")
    print("[*] now run: python bomber.py")
    input("\nPress Enter to exit...")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nbye.")
